package com.auracode.hiposim.feature.report.data

import com.auracode.hiposim.core.network.problemException
import com.auracode.hiposim.feature.simulation.data.FakeSimulationStore
import kotlinx.coroutines.delay
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.ResponseBody
import okhttp3.ResponseBody.Companion.toResponseBody

/**
 * Stand-in for `GET /api/simulations/{id}/report` (`BuildConfig.USE_FAKE_API`). It answers a small valid PDF for a
 * simulation the fake API calculated, and 404 for any other id, like the server. The document only says it is a demo:
 * the real report (summary and payment schedule) is generated by the API.
 */
class FakeReportService(
    private val latencyMillis: Long = 0,
) : ReportService {
    override suspend fun getReport(simulationId: String): ResponseBody {
        if (latencyMillis > 0) delay(latencyMillis)
        FakeSimulationStore.get(simulationId) ?: throw problemException(NOT_FOUND, "Simulation not found.")
        return demoPdf(simulationId).toResponseBody("application/pdf".toMediaType())
    }

    companion object {
        /** Simulated network delay of the app, so the loading state can be seen. */
        const val DEFAULT_LATENCY_MILLIS = 600L
        private const val NOT_FOUND = 404

        /** A one page PDF with correct offsets, so any viewer opens it without repairing it. */
        internal fun demoPdf(simulationId: String): ByteArray {
            val text = "HipoSim - demo report of simulation $simulationId"
            val stream = "BT /F1 14 Tf 72 760 Td ($text) Tj ET"
            val objects =
                listOf(
                    "<< /Type /Catalog /Pages 2 0 R >>",
                    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
                    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R " +
                        "/Resources << /Font << /F1 5 0 R >> >> >>",
                    "<< /Length ${stream.length} >>\nstream\n$stream\nendstream",
                    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
                )
            val out = StringBuilder("%PDF-1.4\n")
            val offsets = mutableListOf<Int>()
            objects.forEachIndexed { index, body ->
                offsets += out.length
                out.append("${index + 1} 0 obj\n$body\nendobj\n")
            }
            val xrefAt = out.length
            out.append("xref\n0 ${objects.size + 1}\n0000000000 65535 f \n")
            offsets.forEach { out.append("%010d 00000 n \n".format(it)) }
            out.append("trailer\n<< /Size ${objects.size + 1} /Root 1 0 R >>\nstartxref\n$xrefAt\n%%EOF\n")
            return out.toString().toByteArray(Charsets.US_ASCII)
        }
    }
}
